const SUPABASE_HOST = /\.supabase\.(com|co)$/i;

export function isSupabaseUrl(url: string): boolean {
  try {
    return SUPABASE_HOST.test(new URL(url).hostname);
  } catch {
    return false;
  }
}

/**
 * The `ssl` option for a node-postgres connection to `url`: Supabase's root
 * pinned and verified for Supabase hosts, otherwise undefined so the
 * connection string's own sslmode (or none, for localhost) applies.
 */
export function pgSslFor(url: string): ConnectionOptions | undefined {
  return isSupabaseUrl(url) ? { ca: SUPABASE_ROOT_CA_2021, rejectUnauthorized: true } : undefined;
}
